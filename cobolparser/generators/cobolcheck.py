"""
CobolCheck test file generator.

Takes a TestPlan and emits valid CobolCheck .cut file content as a string.
"""

from __future__ import annotations

from ..analysis.test_plan import (
    DataSetup,
    ExpectedOutcome,
    TestCase,
    TestPlan,
    TestSuite,
)

# Values that should not be quoted in MOVE/EXPECT statements.
# Includes COBOL figurative constants and CobolCheck keywords like NUMERIC.
_UNQUOTED_VALUES = frozenset(
    {
        "ZERO",
        "ZEROS",
        "ZEROES",
        "SPACE",
        "SPACES",
        "HIGH-VALUE",
        "HIGH-VALUES",
        "LOW-VALUE",
        "LOW-VALUES",
        "QUOTE",
        "QUOTES",
        "ALL",
        "NULL",
        "NULLS",
        "NUMERIC",
    }
)


class CobolCheckGenerator:
    """Generates CobolCheck .cut file content from a TestPlan."""

    def __init__(
        self,
        indent: int = 4,
        include_comments: bool = True,
    ) -> None:
        self._indent = indent
        self._include_comments = include_comments

    def generate(self, test_plan: TestPlan) -> str:
        """Generate complete CobolCheck .cut file content."""
        lines: list[str] = []

        if self._include_comments:
            lines.extend(self._emit_header(test_plan.program_name))

        if not test_plan.test_suites:
            if self._include_comments:
                lines.append(
                    self._emit_comment(
                        "No test suites generated (program may lack "
                        "a PROCEDURE DIVISION)"
                    )
                )
            return "\n".join(lines) + "\n"

        for i, suite in enumerate(test_plan.test_suites):
            if i > 0:
                lines.append("")
            lines.extend(self._emit_test_suite(suite))

        return "\n".join(lines) + "\n"

    def _emit_header(self, program_name: str) -> list[str]:
        """Generate header comment block."""
        return [
            self._emit_comment(f"Generated CobolCheck tests for {program_name}"),
            self._emit_comment("Auto-generated by cobol-parser coverage analyzer"),
            "",
        ]

    def _emit_test_suite(self, suite: TestSuite) -> list[str]:
        """Generate a TESTSUITE block."""
        lines: list[str] = []
        lines.append(f'{self._pad()}TESTSUITE "{suite.name}"')

        for tc in suite.test_cases:
            lines.append("")
            lines.extend(self._emit_test_case(tc))

        return lines

    def _emit_test_case(self, test_case: TestCase) -> list[str]:
        """Generate a TESTCASE block."""
        lines: list[str] = []
        indent = self._pad()
        body_indent = self._pad(2)

        if self._include_comments and test_case.comment:
            lines.append(self._emit_comment(test_case.comment))

        lines.append(f'{indent}TESTCASE "{test_case.name}"')

        for setup in test_case.data_setup:
            lines.extend(self._emit_data_setup(setup))

        lines.append(f"{body_indent}PERFORM {test_case.target_paragraph}")

        for outcome in test_case.expected_outcomes:
            lines.append(self._emit_expected_outcome(outcome))

        return lines

    def _emit_data_setup(self, setup: DataSetup) -> list[str]:
        """Generate a MOVE statement for data setup, with optional comment."""
        lines: list[str] = []
        if self._include_comments and setup.comment:
            lines.append(self._emit_comment(setup.comment))
        value = self._format_cobol_value(setup.value)
        lines.append(f"{self._pad(2)}MOVE {value} TO {setup.target_variable}")
        return lines

    def _emit_expected_outcome(self, outcome: ExpectedOutcome) -> str:
        """Generate an EXPECT statement."""
        value = self._format_cobol_value(outcome.expected_value)
        return (
            f"{self._pad(2)}EXPECT {outcome.variable} " f"{outcome.comparison} {value}"
        )

    def _emit_comment(self, text: str) -> str:
        """Generate a comment line."""
        return f"{self._pad()}*> {text}"

    def _format_cobol_value(self, value: str) -> str:
        """Format a value for use in COBOL MOVE/EXPECT statements."""
        stripped = value.strip()
        upper = stripped.upper()

        # Figurative constants and keywords pass through unquoted
        if upper in _UNQUOTED_VALUES:
            return upper

        # Numeric literals pass through unquoted
        numeric = stripped.lstrip("-").lstrip("+")
        if numeric.replace(".", "", 1).isdigit():
            return stripped

        # Already quoted
        if (stripped.startswith('"') and stripped.endswith('"')) or (
            stripped.startswith("'") and stripped.endswith("'")
        ):
            return stripped

        # String literals need quoting — escape embedded double quotes
        escaped = stripped.replace('"', '""')
        return f'"{escaped}"'

    def _pad(self, level: int = 1) -> str:
        """Return indentation string for the given nesting level."""
        return " " * (self._indent * level)
